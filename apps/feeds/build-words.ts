import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const usage = `pnpm --filter @vibe-idx/feeds words ENGLISH_WORDS.txt INDONESIAN_WORDS_DIR [TITLES.json]

Writes src/common-words.ts: the ordinary words of four and five letters that the tagger tells apart from codes.
ENGLISH_WORDS.txt  one word per line (the MIT-licensed "word-list" package's words.txt)
INDONESIAN_WORDS_DIR  files of one word per line (the MIT-licensed bekicot/indonesian_words, folder "words")
TITLES.json   optional, an array of { title } from Indonesian news: a lowercase word of four or five letters that
              occurs three times or more is added, which covers words the dictionary lacks`;

const [englishFile, indonesianDir, titlesFile] = process.argv.slice(2);
if (!englishFile || !indonesianDir) {
  console.log(usage);
  process.exit(1);
}
const short = /^[a-z]{4,5}$/;
const lines = (text: string) => text.split('\n').map((line) => line.trim().toLowerCase());

const english = new Set(lines(await readFile(englishFile, 'utf8')).filter((w) => short.test(w)));
const indonesian = new Set<string>();
for (const file of await readdir(indonesianDir))
  for (const word of lines(await readFile(join(indonesianDir, file), 'utf8')))
    if (short.test(word)) indonesian.add(word);
if (titlesFile) {
  const counts = new Map<string, number>();
  const titles: { title: string }[] = JSON.parse(await readFile(titlesFile, 'utf8'));
  for (const { title } of titles)
    for (const word of title.match(/(?<![\p{L}\p{N}])\p{Ll}{4,5}(?![\p{L}\p{N}])/gu) ?? [])
      counts.set(word, (counts.get(word) ?? 0) + 1);
  for (const [word, n] of counts) if (n >= 3 && short.test(word)) indonesian.add(word);
}
for (const word of english) indonesian.delete(word);

const list = (words: Set<string>) => [...words].sort().join(' ');
await writeFile(
  new URL('./src/common-words.ts', import.meta.url),
  `// Generated by \`pnpm --filter @vibe-idx/feeds words\`; do not edit. English: the "word-list" package (MIT).
// Indonesian: bekicot/indonesian_words (MIT, KBBI headwords) and words seen three times or more in Indonesian news.
export const english = '${list(english)}';
export const indonesian = '${list(indonesian)}';
`,
);
console.log(`${english.size} English and ${indonesian.size} Indonesian words`);
